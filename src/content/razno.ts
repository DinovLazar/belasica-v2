/** The topic at `slug`, or null — an unknown slug must 404, never render empty. */
export function raznoTopic(slug: string): RaznoTopic | null {
  return RAZNO_TOPICS.find((topic) => topic.slug === slug) ?? null;
}

/**
 * Prev/next in array order. The first topic has no previous and the last no
 * next; a missing neighbour is `null` and renders **nothing** — never a
 * disabled card, which would imply a topic that does not exist.
 */
export function raznoNeighbours(slug: string): {
  previous: RaznoTopic | null;
  next: RaznoTopic | null;
} {
  const index = RAZNO_TOPICS.findIndex((topic) => topic.slug === slug);
  if (index === -1) return { previous: null, next: null };
  return {
    previous: RAZNO_TOPICS[index - 1] ?? null,
    next: RAZNO_TOPICS[index + 1] ?? null,
  };
}
